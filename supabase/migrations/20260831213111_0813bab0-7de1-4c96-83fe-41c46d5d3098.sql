-- ============ SUPPORT SAV ============
CREATE TABLE public.support_tickets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_number bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) UNIQUE,
  user_id uuid NOT NULL,
  user_kind text NOT NULL DEFAULT 'client',
  category text NOT NULL,
  subject text NOT NULL,
  status text NOT NULL DEFAULT 'new',
  origin_path text,
  assigned_admin uuid,
  last_message_at timestamptz NOT NULL DEFAULT now(),
  last_admin_reply_at timestamptz,
  user_unread boolean NOT NULL DEFAULT false,
  admin_unread boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT support_tickets_status_check CHECK (status IN ('new','in_progress','waiting_user','resolved','closed')),
  CONSTRAINT support_tickets_kind_check CHECK (user_kind IN ('client','driver'))
);

CREATE INDEX support_tickets_user_idx ON public.support_tickets(user_id, created_at DESC);
CREATE INDEX support_tickets_status_idx ON public.support_tickets(status, last_message_at DESC);

GRANT SELECT, INSERT, UPDATE ON public.support_tickets TO authenticated;
GRANT ALL ON public.support_tickets TO service_role;
ALTER TABLE public.support_tickets ENABLE ROW LEVEL SECURITY;

CREATE POLICY "tickets_select_own_or_admin" ON public.support_tickets
  FOR SELECT TO authenticated
  USING (user_id = auth.uid() OR public.is_admin(auth.uid()));

CREATE POLICY "tickets_insert_own" ON public.support_tickets
  FOR INSERT TO authenticated
  WITH CHECK (user_id = auth.uid());

CREATE POLICY "tickets_update_admin" ON public.support_tickets
  FOR UPDATE TO authenticated
  USING (public.is_admin(auth.uid()))
  WITH CHECK (public.is_admin(auth.uid()));

CREATE TABLE public.support_messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id uuid NOT NULL REFERENCES public.support_tickets(id) ON DELETE CASCADE,
  author_id uuid,
  author_kind text NOT NULL,
  body text NOT NULL,
  attachment_path text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT support_messages_author_kind_check CHECK (author_kind IN ('user','admin'))
);

CREATE INDEX support_messages_ticket_idx ON public.support_messages(ticket_id, created_at);

GRANT SELECT, INSERT ON public.support_messages TO authenticated;
GRANT ALL ON public.support_messages TO service_role;
ALTER TABLE public.support_messages ENABLE ROW LEVEL SECURITY;

CREATE POLICY "support_messages_select" ON public.support_messages
  FOR SELECT TO authenticated
  USING (
    public.is_admin(auth.uid())
    OR EXISTS (SELECT 1 FROM public.support_tickets t WHERE t.id = ticket_id AND t.user_id = auth.uid())
  );

CREATE POLICY "support_messages_insert" ON public.support_messages
  FOR INSERT TO authenticated
  WITH CHECK (
    author_id = auth.uid()
    AND (
      (author_kind = 'admin' AND public.is_admin(auth.uid()))
      OR (
        author_kind = 'user'
        AND EXISTS (
          SELECT 1 FROM public.support_tickets t
          WHERE t.id = ticket_id AND t.user_id = auth.uid() AND t.status <> 'closed'
        )
      )
    )
  );

-- Synchronisation du ticket à chaque message
CREATE OR REPLACE FUNCTION public.support_message_touch_ticket()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.author_kind = 'admin' THEN
    UPDATE public.support_tickets
      SET last_message_at = now(),
          updated_at = now(),
          last_admin_reply_at = now(),
          user_unread = true,
          admin_unread = false,
          assigned_admin = COALESCE(assigned_admin, NEW.author_id),
          status = CASE WHEN status IN ('new','in_progress') THEN 'waiting_user' ELSE status END
      WHERE id = NEW.ticket_id;
  ELSE
    UPDATE public.support_tickets
      SET last_message_at = now(),
          updated_at = now(),
          admin_unread = true,
          user_unread = false,
          status = CASE WHEN status IN ('waiting_user','resolved') THEN 'in_progress' ELSE status END
      WHERE id = NEW.ticket_id;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER support_message_touch_ticket
AFTER INSERT ON public.support_messages
FOR EACH ROW EXECUTE FUNCTION public.support_message_touch_ticket();

CREATE TRIGGER support_tickets_updated_at
BEFORE UPDATE ON public.support_tickets
FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

