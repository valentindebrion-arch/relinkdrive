-- ============ HISTORIQUE ADMIN ============
ALTER TABLE public.audit_logs ADD COLUMN IF NOT EXISTS support_ticket_id uuid;
ALTER TABLE public.audit_logs ADD COLUMN IF NOT EXISTS target_user_id uuid;
CREATE INDEX IF NOT EXISTS audit_logs_target_idx ON public.audit_logs(target_user_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.admin_log_change(
  _target_user_id uuid,
  _action text,
  _field text,
  _old_value jsonb,
  _new_value jsonb,
  _reason text DEFAULT NULL,
  _ticket_id uuid DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  _id uuid;
BEGIN
  IF NOT public.is_admin(auth.uid()) THEN
    RAISE EXCEPTION 'forbidden';
  END IF;
  INSERT INTO public.audit_logs (actor_id, action, resource, resource_id, target_user_id, old_value, new_value, reason, support_ticket_id)
  VALUES (auth.uid(), _action, _field, _target_user_id, _target_user_id, _old_value, _new_value, _reason, _ticket_id)
  RETURNING id INTO _id;
  RETURN _id;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_log_change(uuid, text, text, jsonb, jsonb, text, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_log_change(uuid, text, text, jsonb, jsonb, text, uuid) TO authenticated;

-- Correction administrative du sexe (SAV) : contourne le quota, réaligne Woman for Woman
CREATE OR REPLACE FUNCTION public.admin_set_user_gender(_user_id uuid, _gender text, _ticket_id uuid DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  _old text;
BEGIN
  IF NOT public.is_admin(auth.uid()) THEN
    RAISE EXCEPTION 'forbidden';
  END IF;
  IF _gender IS NULL OR _gender NOT IN ('female','male','undisclosed') THEN
    RAISE EXCEPTION 'invalid_gender';
  END IF;

  SELECT gender INTO _old FROM public.profiles WHERE id = _user_id FOR UPDATE;
  UPDATE public.profiles SET gender = _gender WHERE id = _user_id;

  UPDATE public.driver_profiles
    SET gender = _gender,
        booking_theme = CASE WHEN _gender <> 'female' AND booking_theme = 'women_for_women'
                             THEN 'relink_classic' ELSE booking_theme END,
        woman_for_woman = CASE WHEN _gender <> 'female' THEN false ELSE woman_for_woman END,
        women_for_women_eligible = CASE WHEN _gender <> 'female' THEN false ELSE women_for_women_eligible END
    WHERE user_id = _user_id;

  PERFORM public.admin_log_change(_user_id, 'admin.gender_update', 'gender',
    to_jsonb(_old), to_jsonb(_gender), 'Correction SAV', _ticket_id);

  RETURN jsonb_build_object('gender', _gender, 'previous', _old);
END;
$$;

REVOKE ALL ON FUNCTION public.admin_set_user_gender(uuid, text, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_set_user_gender(uuid, text, uuid) TO authenticated;